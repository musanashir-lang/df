export function tentukanSuratTerakhirDariHafalan(jumlahHafalan: string): string {
  const match = jumlahHafalan.match(/(\d+)\s*juz/i);
  const juz = match ? parseInt(match[1], 10) : 0;
  if (juz >= 16) return '20. Ta-Ha';
  if (juz >= 13) return '15. Al-Hijr';
  if (juz >= 10) return '9. At-Taubah';
  if (juz >= 7) return "6. Al-An'am";
  if (juz >= 5) return '4. An-Nisa';
  if (juz >= 3) return "3. Ali 'Imran";
  if (juz >= 2) return '67. Al-Mulk';
  if (juz >= 1) return '78. An-Naba';
  return '114. An-Nas';
}

